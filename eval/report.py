"""Stage 3: render metrics.json + grades.json into RESULTS.md and a chart PNG.

Everything in RESULTS.md is computed from the data — tables, task lists, and
counts. Interpretation belongs in FINDINGS.md, written by a human.
"""

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = Path(__file__).parent
METRICS_PATH = HERE / "metrics.json"
GRADES_PATH = HERE / "grades.json"
CHART_PATH = HERE / "metrics_chart.png"
REPORT_PATH = HERE.parent / "RESULTS.md"

CONDITIONS = ["base_zero_shot", "base_few_shot", "instruct_zero_shot", "instruct_few_shot"]
LABELS = {"base_zero_shot": "Base / zero-shot", "base_few_shot": "Base / few-shot",
          "instruct_zero_shot": "Instruct / zero-shot", "instruct_few_shot": "Instruct / few-shot"}

# palette: categorical slots 1-2 (validated), chrome inks, light surface
BASE_COLOR, INSTRUCT_COLOR = "#2a78d6", "#eb6834"
SURFACE, INK, MUTED, GRID, BASELINE = "#fcfcfb", "#0b0b0b", "#898781", "#e1e0d9", "#c3c2b7"


def style_axis(ax):
    ax.set_facecolor(SURFACE)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(BASELINE)
    ax.tick_params(colors=MUTED, length=0)
    ax.yaxis.grid(True, color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def grouped_bars(ax, values, errs=None, unit="%"):
    """Two groups (zero/few) x two entities (base/instruct), 2px-equivalent gap."""
    x = [0, 1]
    width, gap = 0.32, 0.03
    for i, (model, color) in enumerate([("base", BASE_COLOR), ("instruct", INSTRUCT_COLOR)]):
        xs = [xi + (i - 0.5) * (width + gap) for xi in x]
        vals = [values[f"{model}_zero_shot"], values[f"{model}_few_shot"]]
        bars = ax.bar(xs, vals, width=width, color=color,
                      label=f"{model.capitalize()} model", zorder=3)
        tops = list(vals)
        if errs:
            ci = [errs[f"{model}_{s}_shot"] for s in ("zero", "few")]
            ax.errorbar(xs, vals,
                        yerr=[[v - lo for v, (lo, _) in zip(vals, ci)],
                              [hi - v for v, (_, hi) in zip(vals, ci)]],
                        fmt="none", ecolor=MUTED, elinewidth=1.2, capsize=3, zorder=4)
            tops = [hi for (_, hi) in ci]
        for rect, v, top in zip(bars, vals, tops):
            ax.text(rect.get_x() + rect.get_width() / 2, top + 0.03,
                    f"{v * 100:.0f}%", ha="center", va="bottom",
                    fontsize=9, color=INK, zorder=5)
    ax.set_xticks(x, ["Zero-shot", "Few-shot"], fontsize=10, color=INK)


def make_chart(metrics):
    conds = metrics["conditions"]
    acc = {c: conds[c]["overall"]["accuracy"] for c in CONDITIONS}
    cis = {c: conds[c]["overall"]["wilson_95ci"] for c in CONDITIONS}
    drift = {c: conds[c]["behavior"]["drift_rate"] for c in CONDITIONS}

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(9, 3.9), dpi=200,
                                   layout="constrained")
    fig.patch.set_facecolor(SURFACE)

    style_axis(ax1)
    grouped_bars(ax1, acc, errs=cis)
    ax1.set_title("Accuracy on 20 tasks (Wilson 95% CI)", fontsize=10,
                  color=INK, loc="left", pad=10)

    style_axis(ax2)
    grouped_bars(ax2, drift)
    ax2.set_title("Drift rate — output runs past the answer", fontsize=10,
                  color=INK, loc="left", pad=10)

    for ax in (ax1, ax2):
        ax.set_ylim(0, 1.02)
        ax.set_yticks([0, 0.25, 0.5, 0.75, 1.0],
                      ["0%", "25%", "50%", "75%", "100%"], fontsize=8)

    fig.legend(*ax1.get_legend_handles_labels(), loc="outside upper right",
               ncols=2, frameon=False, fontsize=9, labelcolor=INK)
    fig.savefig(CHART_PATH, facecolor=SURFACE)
    plt.close(fig)


def md_table(header, rows):
    lines = ["| " + " | ".join(header) + " |",
             "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def main():
    metrics = json.loads(METRICS_PATH.read_text(encoding="utf-8"))
    grades = json.loads(GRADES_PATH.read_text(encoding="utf-8"))
    conds = metrics["conditions"]
    make_chart(metrics)

    parts = []
    parts.append(
        "# Results: base vs instruct, zero-shot vs few-shot\n\n"
        "Generated by `eval/report.py` — do not edit by hand. Regenerate with:\n\n"
        "```\ncd eval\npython grade.py && python metrics.py && python report.py\n```\n\n"
        "Grading rules are documented in `eval/README.md`. Interpretation lives in "
        "`FINDINGS.md`; every number here is computed from `base_vs_instruct.json`.\n\n"
        "> **Disclosure.** The grading pipeline in `eval/` and the cell-by-cell "
        "grading audit were built and run by an AI assistant (Claude) on my "
        "behalf, including the extraction rules and the hand-verification of "
        "all 80 graded cells. The model completions being graded, the task "
        "set, and the interpretation in `FINDINGS.md` are my own work. I state "
        "this so readers can weigh the methodology knowing who produced it.\n"
    )
    parts.append(f"![accuracy and drift by condition](eval/metrics_chart.png)\n")

    rows = []
    for c in sorted(CONDITIONS, key=lambda c: -conds[c]["overall"]["accuracy"]):
        o, b = conds[c]["overall"], conds[c]["behavior"]
        lo, hi = o["wilson_95ci"]
        rows.append([LABELS[c], f"**{o['accuracy']:.0%}** ({o['correct']}/{o['n']})",
                     f"{lo:.0%}–{hi:.0%}", f"{b['drift_rate']:.0%}",
                     f"{b['mean_repetition']:.2f}", f"{b['mean_chars']:.0f}",
                     len(b["refusals"]), len(b["empty_outputs"])])
    parts.append("## Headline metrics\n\n" + md_table(
        ["Condition", "Accuracy", "95% CI", "Drift", "Repetition", "Mean chars",
         "Refusals", "Empty"], rows) +
        "\n\nDrift = output continues past the answer into self-generated Q/A pairs "
        "or template text. Repetition = mean fraction of duplicate lines per output. "
        "Refusal/empty counts are out of 20 tasks.\n")

    cats = sorted(conds[CONDITIONS[0]]["by_category"])
    rows = []
    for cat in cats:
        row = [cat]
        for c in CONDITIONS:
            blk = conds[c]["by_category"][cat]
            row.append(f"{blk['correct']}/{blk['n']}")
        rows.append(row)
    parts.append("## Accuracy by category\n\n" + md_table(
        ["Category"] + [LABELS[c] for c in CONDITIONS], rows) +
        "\n\nCell counts are small (3–4 tasks per category); read direction, "
        "not magnitude.\n")

    rows = []
    for d in ("easy", "medium", "hard"):
        row = [d]
        for c in CONDITIONS:
            blk = conds[c]["by_difficulty"][d]
            row.append(f"{blk['correct']}/{blk['n']}")
        rows.append(row)
    parts.append("## Accuracy by difficulty\n\n" + md_table(
        ["Difficulty"] + [LABELS[c] for c in CONDITIONS], rows) + "\n")

    key_pairs = [
        ("base_zero_shot", "instruct_zero_shot", "Instruction tuning (zero-shot)"),
        ("base_zero_shot", "base_few_shot", "Few-shot examples, base model"),
        ("instruct_zero_shot", "instruct_few_shot", "Few-shot examples, instruct model"),
        ("base_few_shot", "instruct_zero_shot", "Best base recipe vs best instruct recipe"),
    ]
    rows = []
    for a, b, label in key_pairs:
        pw = metrics["pairwise"][f"{a}__vs__{b}"]
        rows.append([label,
                     f"{LABELS[a]}: tasks {pw['only_first_correct'] or '—'}",
                     f"{LABELS[b]}: tasks {pw['only_second_correct'] or '—'}",
                     pw["mcnemar_exact_p"]])
    parts.append("## Head-to-head: which tasks flip\n\n" + md_table(
        ["Comparison", "Only first correct", "Only second correct", "exact p"], rows) +
        "\n\np is an exact two-sided McNemar/binomial test on the discordant tasks. "
        "With n=20 nothing here reaches significance; the task lists are the "
        "evidence, the p-values are honesty.\n")

    nr = metrics["needs_review"]
    ov = metrics["overrides_applied"]
    lines = [f"- task {x['task_id']}, `{x['condition']}` — extracted: `{x['extracted']}`"
             for x in nr]
    parts.append("## Grading audit\n\n"
                 f"Cells where extraction failed and a human should rule "
                 f"(`eval/overrides.json`): {len(nr)}\n\n" + "\n".join(lines) + "\n")
    if ov:
        lines = [f"- task {x['task_id']}, `{x['condition']}`: auto={x['auto']} -> "
                 f"final={x['final']} — {x['reason']}" for x in ov]
        parts.append("### Overrides applied\n\n" + "\n".join(lines) + "\n")

    REPORT_PATH.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {REPORT_PATH.name} and {CHART_PATH.relative_to(HERE.parent)}")


if __name__ == "__main__":
    main()
